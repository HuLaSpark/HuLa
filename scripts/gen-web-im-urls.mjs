// Generates src/platform/web/commands/imUrls.ts from the Rust ImUrl mapping
// (src-tauri/src/im_request_client.rs), so the browser build calls exactly the
// same endpoints as the desktop build. Run: node scripts/gen-web-im-urls.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const rust = readFileSync(resolve(root, 'src-tauri/src/im_request_client.rs'), 'utf8')

const routes = new Map()
for (const m of rust.matchAll(/ImUrl::(\w+)\s*=>\s*\{?\s*\(\s*http::Method::(\w+)\s*,\s*"([^"]*)"\s*,?\s*\)/g)) {
  routes.set(m[1], [m[2], m[3]])
}
const names = new Map()
for (const m of rust.matchAll(/"(\w+)"\s*=>\s*Ok\(\s*ImUrl::(\w+)\s*\)/g)) {
  names.set(m[1], m[2])
}

const lines = []
const missing = []
for (const [name, variant] of [...names].sort(([a], [b]) => a.localeCompare(b))) {
  const route = routes.get(variant)
  if (!route) {
    missing.push(`${name} -> ${variant}`)
    continue
  }
  lines.push(`  ${JSON.stringify(name)}: [${JSON.stringify(route[0])}, ${JSON.stringify(route[1])}],`)
}
if (missing.length) {
  console.error('no route for:', missing.join(', '))
  process.exit(1)
}

const out = `// Generated by scripts/gen-web-im-urls.mjs from src-tauri/src/im_request_client.rs. Do not edit.
export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'DELETE' | 'PATCH'

export const IM_URLS: Record<string, [HttpMethod, string]> = {
${lines.join('\n')}
}
`
writeFileSync(resolve(root, 'src/platform/web/commands/imUrls.ts'), out)
console.log(`imUrls.ts: ${lines.length} urls from ${routes.size} routes`)
